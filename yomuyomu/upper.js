// ・表記はふつうの漢字かな交じり（分かち書きなし）。

const TFU = ["正しい", "まちがっている", "判断できない"];
const tfU = (a) => TFU.map((t) => ({ text: t, ok: t === a }));
const SDU = (same) => [{ text: "同じである", ok: same }, { text: "異なる", ok: !same }];
const ASK_TF = (s) => `本文の内容が正しいとき、次の文の内容は「正しい」「まちがっている」「判断できない」のどれか。\n「${s}」`;
const ASK_SAME = "アとイの内容は同じか。「同じである」「異なる」のどちらかで答えなさい。";
const ASK_FILL = (s) => `本文の内容に合うように、（　）にあてはまる最も適当なものを選びなさい。\n${s}`;
const ASK_REF = (w) => `本文中の「${w}」が指すものとして、最も適当なものを選びなさい。`;
const NU = ["佐藤さん", "鈴木さん", "高橋さん", "田中さん", "伊藤さん", "渡辺さん", "山本さん", "中村さん"];

// 手づくりの問題（いくつかの中から1つ）
//   {tf:答え, p:本文, s:文}  {same:true/false, a, b}  {p, q:問い, c:[選択肢], ans:番号}
function P(o) {
  if (o.stmts) { const [s, a, e] = pick(o.stmts); return P({ tf: a, p: o.p, s, e, n: o.n }); }
  if (o.tf) return build({ passage: o.p, ask: ASK_TF(o.s), choices: tfU(o.tf), fixed: true, explain: o.e, note: o.n });
  if (o.same !== undefined) return build({ passage: o.a, passage2: o.b, ask: ASK_SAME, choices: SDU(o.same), fixed: true, explain: o.e, note: o.n });
  return build({ passage: o.p, ask: o.q, choices: o.c.map((t, i) => ({ text: t, ok: i === (o.ans || 0) })), explain: o.e, note: o.n });
}
const pool = (field, id, from, to, items) => tpl(field, id, from, to, () => P(pick(items)));

